public class Main {

    // 1. Definition of the method
    // 'void' means it returns nothing, '()' means no parameters
    public static void displayMessage() {
        System.out.println("Hello! This method has no parameters and no return type.");
    }

    public static void main(String[] args) {
        // 2. Invoking (calling) the method
        displayMessage(); 
    }
}
